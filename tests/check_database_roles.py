"""Integration check against a disposable CI-only database; never production."""

import os
from pathlib import Path
import subprocess
import sys

import psycopg
from psycopg import sql

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from deploy.configure_db_roles import configure


def main():
    env = dict(os.environ)
    if env.get("POSTGRES_DB") != "score_it_ci" or env.get("DB_ENGINE") != "postgresql":
        raise SystemExit("Only the disposable score_it_ci database may run this test.")
    env.update(DB_USER="score_it_runtime_ci", DB_PASSWORD="runtime-ci-only-password",
               DB_MIGRATION_USER="score_it_migrate_ci", DB_MIGRATION_PASSWORD="migration-ci-only-password")
    admin_args = dict(host=env["DB_HOST"], port=env.get("DB_PORT", "5432"), dbname=env["POSTGRES_DB"],
                      user=env["POSTGRES_USER"], password=env["POSTGRES_PASSWORD"])
    configure(env)
    with psycopg.connect(**admin_args) as admin:
        assert not admin.execute("SELECT 1 FROM pg_roles WHERE rolname=%s", (env["DB_USER"],)).fetchone()
        before = admin.execute("SELECT count(*) FROM poker_task").fetchone()[0]
    configure(env, apply=True)
    migration_env = dict(env, DB_USER=env["DB_MIGRATION_USER"], DB_PASSWORD=env["DB_MIGRATION_PASSWORD"])
    subprocess.run([sys.executable, "manage.py", "migrate", "--noinput"], env=migration_env, check=True)
    subprocess.run([sys.executable, "manage.py", "check_database_security"], env=env, check=True)
    with psycopg.connect(**dict(admin_args, user=env["DB_MIGRATION_USER"], password=env["DB_MIGRATION_PASSWORD"])) as migration:
        migration.execute("CREATE TABLE public.poker_security_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text)")
    with psycopg.connect(**dict(admin_args, user=env["DB_USER"], password=env["DB_PASSWORD"])) as runtime:
        assert runtime.execute("SELECT count(*) FROM poker_task").fetchone()[0] == before
        runtime.execute("INSERT INTO poker_security_probe (value) VALUES ('before')")
        runtime.execute("UPDATE poker_security_probe SET value='after'")
        assert runtime.execute("SELECT value FROM poker_security_probe").fetchone()[0] == 'after'
        runtime.execute("DELETE FROM poker_security_probe")
        for statement in ("CREATE TABLE public.poker_forbidden (id integer)", "CREATE TEMP TABLE forbidden (id integer)",
                          "CREATE ROLE score_it_forbidden_ci", "TRUNCATE poker_security_probe",
                          "ALTER TABLE poker_security_probe ADD COLUMN forbidden text"):
            try:
                with runtime.transaction():
                    runtime.execute(statement)
            except psycopg.errors.InsufficientPrivilege:
                pass
            else:
                raise AssertionError("Runtime executed forbidden DDL/administration")
    configure(env, apply=True)
    subprocess.run([sys.executable, "manage.py", "check_database_security"], env=env, check=True)
    # NOINHERIT still permits SET ROLE: membership itself must be rejected.
    with psycopg.connect(**admin_args) as admin:
        admin.execute(sql.SQL("GRANT {} TO {}").format(sql.Identifier(env["DB_MIGRATION_USER"]), sql.Identifier(env["DB_USER"])))
    result = subprocess.run([sys.executable, "manage.py", "check_database_security"], env=env, capture_output=True)
    assert result.returncode != 0, "Runtime membership of the migration role was accepted"
    with psycopg.connect(**admin_args) as admin:
        admin.execute(sql.SQL("REVOKE {} FROM {}").format(sql.Identifier(env["DB_MIGRATION_USER"]), sql.Identifier(env["DB_USER"])))
    subprocess.run([sys.executable, "manage.py", "check_database_security"], env=env, check=True)
    print("DATABASE_ROLES_VERIFIED: data retained; future DML allowed; DDL/admin denied; repeat apply works.")


if __name__ == "__main__":
    main()
